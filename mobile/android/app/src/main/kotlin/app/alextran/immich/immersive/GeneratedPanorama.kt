package app.alextran.immich.immersive

import app.alextran.immich.immersive.scene.SceneFile
import kotlin.math.atan2

/**
 * A panorama Immuch360 generated beyond the edges of a photo, or its 3D version, as the sphere of the immersive viewer
 * reads it from the head of the file it shows (design-final 2026-10-27, sections 5 and 8.1, lot P4): our packet,
 * Immuch360:Kind Panorama360 or StereoPanorama360 with Origin GeneratedContent, where the photo itself lies
 * (PhotoYaw, PhotoPitch, PhotoHfov, PhotoVfov) and the quality flags.
 *
 * The viewer reads the head itself, for every photo it shows on a sphere: the one the app opened and those previous and
 * next reach (ImmersiveApi.showAdjacent carries no labels), from the server, a share or the headset alike. The labels
 * only carry the translated texts (the generatedNotice key of stereoLabels, and the flags), which the app sends with
 * every opening; their English texts stand in for a missing one.
 *
 * What it gives: "Generated by AI beyond the photo's edges" passing on every path of the sphere (whole, front half,
 * top and bottom, side by side) and kept in the panel with the flags of the file ("The seam may be visible"); the yaw
 * the sphere opens at, so that the photo is where the user looks; and the photo for [PanoramaOutline]. The 3D version
 * of a 360° photo of the user (Origin EstimatedDepth) says "Relief estimated by AI" instead: nothing was invented
 * beyond its edges.
 *
 * Pure JVM, tested by GeneratedPanoramaTest against the packets the Dart side writes.
 */
internal object GeneratedPanorama {
  /** The bytes of the head searched for the packet, as for a scene (SceneFile.HEAD_BYTES) */
  const val HEAD_BYTES = SceneFile.HEAD_BYTES

  const val KIND_PANORAMA = "Panorama360"
  const val KIND_STEREO_PANORAMA = "StereoPanorama360"
  const val ORIGIN_GENERATED = "GeneratedContent"
  const val ORIGIN_ESTIMATED = "EstimatedDepth"

  /** The version of our packets whose photo this build reads (Immuch360:FormatVersion) */
  const val SUPPORTED_FORMAT_VERSION = 1

  /** The key of stereoLabels for the passing text (generatedNoticeLabelKey of stereo_pair_requests.dart) */
  const val LABEL_NOTICE = "generatedNotice"

  /** The keys of the lines of the flags in the panel: this prefix and the flag as written in QualityFlags */
  const val LABEL_FLAG_PREFIX = "panoramaFlag_"

  /** The English texts of the labels, for a key the app did not send */
  val englishLabels: Map<String, String> =
    mapOf(
      LABEL_NOTICE to "Generated by AI beyond the photo's edges",
      LABEL_FLAG_PREFIX + "seam" to "The seam may be visible",
      LABEL_FLAG_PREFIX + "mostlyInvented" to "Most of this panorama is invented",
      LABEL_FLAG_PREFIX + "fovGuessed" to "Field of view guessed: shapes may be off",
      LABEL_FLAG_PREFIX + "hiddenAreas" to "Large hidden areas were filled in",
      LABEL_FLAG_PREFIX + "lowRelief" to "Little depth found: the relief may be weak",
    )

  /** The translated text of [key], else its English text */
  fun label(labels: Map<String, String>, key: String): String =
    labels[key]?.takeIf { it.isNotBlank() } ?: englishLabels[key] ?: key

  /**
   * Our packet of a panorama in the first [HEAD_BYTES] of a file, [head] being at least those (found as the Dart side
   * finds it, ImmersiveXmp.findIn: by our namespace, then the packet around it); null when the head holds none, or our
   * packet of another kind
   */
  fun readHead(head: ByteArray): PanoramaHead? {
    val count = minOf(head.size, HEAD_BYTES)
    // ISO 8859-1 keeps one character per byte, so the places found in the text are places in the bytes
    val text = String(head, 0, count, Charsets.ISO_8859_1)
    var from = 0
    while (true) {
      val at = text.indexOf(SceneFile.NAMESPACE, from)
      if (at < 0) return null
      val start =
        text.lastIndexOf("<x:xmpmeta", at).takeIf { it >= 0 } ?: text.lastIndexOf("<rdf:RDF", at).coerceAtLeast(0)
      val close = text.indexOf("</x:xmpmeta>", at)
      val end =
        if (close >= 0) close + "</x:xmpmeta>".length
        else text.indexOf("</rdf:RDF>", at).let { if (it < 0) count else it + "</rdf:RDF>".length }
      parsePacket(String(head, start, end - start, Charsets.UTF_8))?.let { return it }
      from = at + SceneFile.NAMESPACE.length
    }
  }

  /** What [packet] says of a panorama, null when it binds no prefix to our namespace or names another kind */
  fun parsePacket(packet: String): PanoramaHead? {
    val prefix =
      Regex("xmlns:([A-Za-z_][\\w.-]*)\\s*=\\s*[\"']${Regex.escape(SceneFile.NAMESPACE)}[\"']")
        .find(packet)
        ?.groupValues
        ?.get(1) ?: return null
    fun value(name: String): String? {
      val qualified = Regex.escape("$prefix:$name")
      Regex("(?<![\\w:.-])$qualified\\s*=\\s*(?:\"([^\"]*)\"|'([^']*)')").find(packet)?.let { match ->
        return SceneFile.unescape(match.groups[1]?.value ?: match.groups[2]?.value ?: "")
      }
      return Regex("<$qualified(?:\\s[^>]*)?>([^<]*)</$qualified\\s*>").find(packet)?.let {
        SceneFile.unescape(it.groupValues[1].trim())
      }
    }
    val kind = value("Kind")
    if (kind != KIND_PANORAMA && kind != KIND_STEREO_PANORAMA) return null
    fun decimal(name: String): Double? = value(name)?.trim()?.toDoubleOrNull()?.takeIf { it.isFinite() }
    return PanoramaHead(
      formatVersion = value("FormatVersion")?.trim()?.toIntOrNull(),
      kind = kind,
      origin = value("Origin"),
      region = PhotoRegion.of(decimal("PhotoYaw"), decimal("PhotoPitch"), decimal("PhotoHfov"), decimal("PhotoVfov")),
      flags = value("QualityFlags").orEmpty().split(',').map { it.trim() }.filter { it.isNotEmpty() },
    )
  }

  /**
   * The passing text of a photo on a sphere whose head says [head], whatever the sphere shows of it ([layout] and
   * [coverage]: the whole sphere, its front half, top and bottom, side by side): "Generated by AI beyond the photo's
   * edges" for a panorama we generated or its 3D version, "Relief estimated by AI" for the 3D version of a 360° photo
   * of the user; null for any other photo
   */
  @Suppress("UNUSED_PARAMETER")
  fun noticeOnSphere(
    head: PanoramaHead?,
    labels: Map<String, String>,
    layout: ImmersiveStereoLayout,
    coverage: ImmersiveSphereCoverage,
  ): String? =
    when {
      head == null -> null
      head.isGenerated -> label(labels, LABEL_NOTICE)
      head.isEstimatedRelief -> StereoComposer.label(labels, StereoComposer.LABEL_RELIEF_ESTIMATED)
      else -> null
    }

  /**
   * The lines the panel keeps: the sentence of [noticeOnSphere], then the flags of the file this build knows on one
   * line, so that the four a 3D version may carry fit in the four lines of the panel
   */
  fun detailLines(head: PanoramaHead?, labels: Map<String, String>): List<String> {
    val notice =
      noticeOnSphere(head, labels, ImmersiveStereoLayout.MONO, ImmersiveSphereCoverage.FULL) ?: return emptyList()
    val flags = head?.flags.orEmpty().map { LABEL_FLAG_PREFIX + it }.filter { it in englishLabels }
    return if (flags.isEmpty()) listOf(notice) else listOf(notice, flags.joinToString(" · ") { label(labels, it) })
  }

  /**
   * The yaw of a gaze whose horizontal direction in the world of the Spatial SDK is [forwardX], [forwardZ]: 0 along +z,
   * positive towards +x, the way Quaternion(0f, yaw, 0f) turns (SdkFrame); 0 for a gaze straight up or down
   */
  fun gazeYawDegrees(forwardX: Double, forwardZ: Double): Double =
    if (forwardX == 0.0 && forwardZ == 0.0) 0.0 else Math.toDegrees(atan2(forwardX, forwardZ))

  /**
   * The yaw to give the sphere of a panorama whose photo is [region], for the photo to open where the user looks
   * ([gazeYawDegrees]): a point at the longitude l of the panorama lies at the world yaw l + yaw minus
   * [skyboxYawDegrees], the rotation that puts the centre column ahead (SKYBOX_YAW_DEGREES)
   */
  fun openingYaw(gazeYawDegrees: Double, region: PhotoRegion, skyboxYawDegrees: Float): Float =
    normalizeDegrees(skyboxYawDegrees + gazeYawDegrees - region.yaw).toFloat()

  /** [degrees] within -180 (excluded) and 180 */
  fun normalizeDegrees(degrees: Double): Double {
    val wrapped = ((degrees % 360.0) + 360.0) % 360.0
    return if (wrapped > 180.0) wrapped - 360.0 else wrapped
  }
}

/**
 * Where the photo itself lies in a panorama made from it, in degrees: the centre of its frame ([yaw] from the centre
 * column of the panorama, positive to the right; [pitch] positive upwards) and its fields of view (PhotoRegion of
 * immersive_xmp.dart)
 */
internal data class PhotoRegion(val yaw: Double, val pitch: Double, val hfov: Double, val vfov: Double) {
  companion object {
    /** The region of these values, null when one is missing or cannot be right; the yaw brought within -180..180 */
    fun of(yaw: Double?, pitch: Double?, hfov: Double?, vfov: Double?): PhotoRegion? {
      if (yaw == null || pitch == null || hfov == null || vfov == null) return null
      if (pitch !in -90.0..90.0 || hfov <= 0.0 || hfov >= 180.0 || vfov <= 0.0 || vfov >= 180.0) return null
      return PhotoRegion(GeneratedPanorama.normalizeDegrees(yaw), pitch, hfov, vfov)
    }
  }
}

/**
 * What our packet at the head of a panorama says: Immuch360:FormatVersion, Kind and Origin as written, the [region] of
 * the photo (null when a field is missing or cannot be right) and the quality flags
 */
internal data class PanoramaHead(
  val formatVersion: Int?,
  val kind: String?,
  val origin: String?,
  val region: PhotoRegion?,
  val flags: List<String>,
) {
  /** Generated by AI beyond the edges of a photo, whatever the version of the packet: the honest side */
  val isGenerated: Boolean
    get() = origin == GeneratedPanorama.ORIGIN_GENERATED

  /**
   * The outline of the photo is drawn on a panorama we generated, not on its 3D version: at 240 m the outline is at
   * infinity, while the relief of the 3D version brings things a few metres away, which the outline would cut
   * (P4-review, m2). The 3D version keeps its sentence and opens with the photo where the user looks.
   */
  val drawsOutline: Boolean
    get() = isGenerated && kind != GeneratedPanorama.KIND_STEREO_PANORAMA

  /** The 3D version of a 360° photo of the user: its relief estimated by AI, nothing invented beyond its edges */
  val isEstimatedRelief: Boolean
    get() = kind == GeneratedPanorama.KIND_STEREO_PANORAMA && origin == GeneratedPanorama.ORIGIN_ESTIMATED

  /** The photo, only from a packet of a version this build reads: a newer one may place it otherwise */
  val readableRegion: PhotoRegion?
    get() = if ((formatVersion ?: 1) <= GeneratedPanorama.SUPPORTED_FORMAT_VERSION) region else null
}
