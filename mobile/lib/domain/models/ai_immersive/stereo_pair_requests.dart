/// A side by side photo for the stereo quad: which eye is on the left, full or half width, and what the file says of
/// itself (our XMP: the relief was estimated and the left eye is the original; another tool's file: unknown)
class SbsPhotoRequest {
  const SbsPhotoRequest({
    this.layout = EyeOrder.leftRight,
    this.eyes = StereoEyes.full,
    this.origin = ImmersiveOrigin.unknown,
    this.leftEye = LeftEyeSource.unknown,
  });

  final EyeOrder layout;
  final StereoEyes eyes;
  final ImmersiveOrigin origin;
  final LeftEyeSource leftEye;

  Map<String, Object> toJson() => {
    'kind': sbsPhotoKind,
    'version': sbsPhotoVersion,
    'layout': layout.json,
    'eyes': eyes.json,
    'origin': origin.json,
    'leftEye': leftEye.json,
  };

  /// The stereoPair JSON of ImmersiveApi.open
  String toJsonString() => jsonEncode(toJson());

  /// The request [json] holds, null for another kind or version or a value this build does not know
  static SbsPhotoRequest? fromJson(Object? json) {
    if (json is! Map || json['kind'] != sbsPhotoKind || json['version'] != sbsPhotoVersion) {
      return null;
    }
    final layout = EyeOrder.fromJson(json['layout']);
    final eyes = StereoEyes.fromJson(json['eyes']);
    if (layout == null || eyes == null) {
      return null;
    }
    return SbsPhotoRequest(
      layout: layout,
      eyes: eyes,
      origin: ImmersiveOrigin.fromJson(json['origin']) ?? ImmersiveOrigin.unknown,
      leftEye: LeftEyeSource.fromJson(json['leftEye']) ?? LeftEyeSource.unknown,
    );
  }

  @override
  bool operator ==(Object other) =>
      other is SbsPhotoRequest &&
      other.layout == layout &&
      other.eyes == eyes &&
      other.origin == origin &&
      other.leftEye == leftEye;

  @override
  int get hashCode => Object.hash(layout, eyes, origin, leftEye);
}

/// How the immersive viewer of the Meta Quest first shows a relief it made: both eyes on the stereo quad, or the photo
/// on a mesh moved by its depth map, which follows the head (2.5D, experimental). The 3D button of the quad switches
/// between them and 2D whatever the request says. Stored by name in the settings (aiReliefQuestMode).
enum ReliefViewMode {
  stereo('stereo'),
  mesh25d('mesh25d');

  const ReliefViewMode(this.json);

  /// The value of "mode" in the depthRelief JSON
  final String json;

  /// The mode of [value]; stereo for a missing value or one this build does not know, the safe default
  static ReliefViewMode fromJson(Object? value) =>
      values.firstWhere((mode) => mode.json == value, orElse: () => ReliefViewMode.stereo);
}

/// A flat photo whose relief the headset estimates: the model file on the headset, its size (checked before loading),
/// its identifier, the key of the cached depth map, the settings of relief-v1, the quarter turns applied to the photo
/// and the mode it first shows in. "mode" is written for 2.5D only: a request without it is a stereo one, as every
/// request was before it existed.
class DepthReliefRequest {
  const DepthReliefRequest({
    required this.model,
    required this.modelSize,
    required this.modelId,
    required this.cacheKey,
    this.parallax = ReliefV1.parallax,
    this.convergence = ReliefV1.convergence,
    this.quarterTurns = 0,
    this.mode = ReliefViewMode.stereo,
  });

  /// Absolute path of the model file on the headset
  final String model;
  final int modelSize;

  /// "depth-anything-v2-small@651415f1" (see [depthModelId])
  final String modelId;

  /// See [reliefCacheKey]
  final String cacheKey;
  final double parallax;
  final double convergence;

  /// Clockwise, 0 to 3
  final int quarterTurns;

  /// How the viewer first shows the relief (see [ReliefViewMode])
  final ReliefViewMode mode;

  Map<String, Object> toJson() => {
    'kind': depthReliefKind,
    'version': depthReliefVersion,
    'model': model,
    'modelSize': modelSize,
    'modelId': modelId,
    'cacheKey': cacheKey,
    'parallax': parallax,
    'convergence': convergence,
    'quarterTurns': quarterTurns,
    if (mode != ReliefViewMode.stereo) 'mode': mode.json,
  };

  /// The stereoPair JSON of ImmersiveApi.open
  String toJsonString() => jsonEncode(toJson());

  /// The request [json] holds, null for another kind or version or a missing field
  static DepthReliefRequest? fromJson(Object? json) {
    if (json is! Map || json['kind'] != depthReliefKind || json['version'] != depthReliefVersion) {
      return null;
    }
    final model = json['model'];
    final modelSize = json['modelSize'];
    final modelId = json['modelId'];
    final cacheKey = json['cacheKey'];
    final parallax = json['parallax'];
    final convergence = json['convergence'];
    final quarterTurns = json['quarterTurns'];
    if (model is! String ||
        modelSize is! int ||
        modelId is! String ||
        cacheKey is! String ||
        parallax is! num ||
        convergence is! num ||
        quarterTurns is! int) {
      return null;
    }
    return DepthReliefRequest(
      model: model,
      modelSize: modelSize,
      modelId: modelId,
      cacheKey: cacheKey,
      parallax: parallax.toDouble(),
      convergence: convergence.toDouble(),
      quarterTurns: quarterTurns & 3,
      mode: ReliefViewMode.fromJson(json['mode']),
    );
  }

  @override
  bool operator ==(Object other) =>
      other is DepthReliefRequest &&
      other.model == model &&
      other.modelSize == modelSize &&
      other.modelId == modelId &&
      other.cacheKey == cacheKey &&
      other.parallax == parallax &&
      other.convergence == convergence &&
      other.quarterTurns == quarterTurns &&
      other.mode == mode;

  @override
  int get hashCode => Object.hash(model, modelSize, modelId, cacheKey, parallax, convergence, quarterTurns, mode);
}

/// A photo that carries a 3D scene (design-final 2026-10-27, sections 3.2 and 8.5): its JPEG preview, then the scene
/// in the [format] glb-layers-v1 in the last [sceneLength] bytes of the file, checked by [sceneSha256]. The sizes are
/// those the gate of the headset weighs before reading the scene, the [safe] zone is in metres after the comfort
/// [scale], [fovDegrees] is the horizontal field of view of the photo. Made from the XMP at the head of the file, which
/// the viewer reads again when the scene opens.
class VolumetricSceneRequest {
  const VolumetricSceneRequest({
    required this.sceneLength,
    required this.sceneSha256,
    required this.meshes,
    required this.vertices,
    required this.triangles,
    required this.textureMax,
    required this.safe,
    required this.fovDegrees,
    this.scale = 1.0,
    this.origin = ImmersiveOrigin.reconstructedFromPhoto,
    this.flags = const [],
    this.format = glbLayersV1,
  });

  /// The bytes of the scene at the end of the file, and their SHA-256 in lowercase hexadecimal
  final int sceneLength;
  final String sceneSha256;

  /// The meshes of the scene (65 535 vertices at most each), their vertices and triangles, and the longest side of
  /// its largest texture
  final int meshes;
  final int vertices;
  final int triangles;
  final int textureMax;

  /// The comfort scale the scene was enlarged by around the eye, 1 most of the time
  final double scale;
  final SceneSafeZone safe;
  final double fovDegrees;
  final ImmersiveOrigin origin;
  final List<ReliefQualityFlag> flags;

  /// See [glbLayersV1]
  final String format;

  Map<String, Object> toJson() => {
    'kind': volumetricSceneKind,
    'version': volumetricSceneVersion,
    'format': format,
    'sceneLength': sceneLength,
    'sceneSha256': sceneSha256,
    'meshes': meshes,
    'vertices': vertices,
    'triangles': triangles,
    'textureMax': textureMax,
    'scale': scale,
    'safe': safe.toJson(),
    'fovDegrees': fovDegrees,
    'origin': origin.json,
    'flags': [
      for (final flag in ReliefQualityFlag.values)
        if (flags.contains(flag)) flag.xmp,
    ],
  };

  /// The stereoPair JSON of ImmersiveApi.open
  String toJsonString() => jsonEncode(toJson());

  static final _sha256Form = RegExp(r'^[0-9a-f]{64}$');

  /// The request [json] holds, null for another kind, version or format, a missing field or a value that cannot be
  /// right. An origin or a flag this build does not know reads as unknown or is left out, as the Kotlin side reads them.
  static VolumetricSceneRequest? fromJson(Object? json) {
    if (json is! Map ||
        json['kind'] != volumetricSceneKind ||
        json['version'] != volumetricSceneVersion ||
        json['format'] != glbLayersV1) {
      return null;
    }
    int? positive(String key) => switch (json[key]) {
      final int value when value > 0 => value,
      _ => null,
    };
    double? finite(String key) => switch (json[key]) {
      final num value when value.isFinite => value.toDouble(),
      _ => null,
    };
    final sceneLength = positive('sceneLength');
    final sceneSha256 = json['sceneSha256'];
    final meshes = positive('meshes');
    final vertices = positive('vertices');
    final triangles = positive('triangles');
    final textureMax = positive('textureMax');
    final scale = finite('scale');
    final safe = SceneSafeZone.fromJson(json['safe']);
    final fovDegrees = finite('fovDegrees');
    final flags = json['flags'];
    if (sceneLength == null ||
        sceneSha256 is! String ||
        !_sha256Form.hasMatch(sceneSha256) ||
        meshes == null ||
        vertices == null ||
        triangles == null ||
        textureMax == null ||
        scale == null ||
        scale <= 0 ||
        safe == null ||
        fovDegrees == null ||
        fovDegrees <= 0 ||
        fovDegrees >= 180 ||
        (flags != null && flags is! List)) {
      return null;
    }
    return VolumetricSceneRequest(
      sceneLength: sceneLength,
      sceneSha256: sceneSha256,
      meshes: meshes,
      vertices: vertices,
      triangles: triangles,
      textureMax: textureMax,
      scale: scale,
      safe: safe,
      fovDegrees: fovDegrees,
      origin: ImmersiveOrigin.fromJson(json['origin']) ?? ImmersiveOrigin.unknown,
      flags: [
        for (final flag in ReliefQualityFlag.values)
          if (flags is List && flags.contains(flag.xmp)) flag,
      ],
    );
  }

  @override
  bool operator ==(Object other) =>
      other is VolumetricSceneRequest &&
      other.format == format &&
      other.sceneLength == sceneLength &&
      other.sceneSha256 == sceneSha256 &&
      other.meshes == meshes &&
      other.vertices == vertices &&
      other.triangles == triangles &&
      other.textureMax == textureMax &&
      other.scale == scale &&
      other.safe == safe &&
      other.fovDegrees == fovDegrees &&
      other.origin == origin &&
      other.flags.length == flags.length &&
      other.flags.every(flags.contains);

  @override
  int get hashCode => Object.hash(
    format,
    sceneLength,
    sceneSha256,
    meshes,
    vertices,
    triangles,
    textureMax,
    scale,
    safe,
    fovDegrees,
    origin,
    Object.hashAll(ReliefQualityFlag.values.where(flags.contains)),
  );
}

/// The folder of the relief cache of the headset in the cache folder of the app (Context.getCacheDir() on Android,
/// getTemporaryDirectory() in Flutter): one `<key>.u16` file per photo, written by the immersive viewer
/// (ReliefCache.FOLDER in Kotlin), sized and cleared by the advanced settings
const reliefCacheFolderName = 'ai-relief';

/// Who a photo is, for the relief cache: its SHA-1 when the asset has one (server, device), otherwise its place on a
/// share
abstract final class ReliefSourceIdentity {
  /// `sha1:<base64>`
  static String sha1(String base64) => 'sha1:$base64';

  /// `share:<source>:<path>:<size>:<date>`, the date in milliseconds since the epoch, UTC
  static String share({required String source, required String path, required int size, required DateTime modified}) =>
      'share:$source:$path:$size:${modified.toUtc().millisecondsSinceEpoch}';
}

/// The text the relief cache key hashes, `<identity>|<model id>|<pipeline>|<parallax>|<convergence>|<quarter turns>`,
/// the doubles in their shortest form ("0.02", "0.5"), the quarter turns from 0 to 3
String reliefCacheKeyText({
  required String identity,
  required String modelId,
  String pipeline = ReliefV1.pipeline,
  double parallax = ReliefV1.parallax,
  double convergence = ReliefV1.convergence,
  int quarterTurns = 0,
}) => '$identity|$modelId|$pipeline|$parallax|$convergence|${quarterTurns & 3}';

/// The key of the depth map of a photo in the cache of the headset, SHA-256 in hexadecimal of [reliefCacheKeyText]: a
/// new model or a new setting misses the cache by itself
String reliefCacheKey({
  required String identity,
  required String modelId,
  String pipeline = ReliefV1.pipeline,
  double parallax = ReliefV1.parallax,
  double convergence = ReliefV1.convergence,
  int quarterTurns = 0,
}) => sha256
    .convert(
      utf8.encode(
        reliefCacheKeyText(
          identity: identity,
          modelId: modelId,
          pipeline: pipeline,
          parallax: parallax,
          convergence: convergence,
          quarterTurns: quarterTurns,
        ),
      ),
    )
    .toString();

/// The kind and version of the request of a Gaussian splat file of another tool (lot S5)
const gaussianSplatKind = 'gaussianSplat';
const gaussianSplatVersion = 1;

/// A Gaussian splat file of another tool (.spz or .ply) for the immersive viewer of a Meta Quest 3 or 3S (lot S5,
/// GaussianSplatSpec on the Kotlin side): what the head of the file said (its [format] as SplatFormat names it, its
/// [formatVersion], [gaussians] and [shDegree]), its size in [fileBytes], the most gaussians the headset shows
/// ([maxGaussians], 50 000, or 150 000 with Large splats), the [tool] a comment of a PLY names, and the file [name],
/// under which the headset remembers the orientation the user chose. The viewer reads the head of the file again,
/// which wins over this JSON; frozen in test/fixtures/ai_immersive/gaussian_splat_contract_v1.json.
class GaussianSplatRequest {
  const GaussianSplatRequest({
    required this.format,
    required this.formatVersion,
    required this.gaussians,
    required this.shDegree,
    required this.fileBytes,
    required this.maxGaussians,
    required this.name,
    this.tool,
  });

  /// spz or ply
  final String format;
  final int formatVersion;
  final int gaussians;
  final int shDegree;
  final int fileBytes;
  final int maxGaussians;
  final String? tool;
  final String name;

  Map<String, Object?> toJson() => {
    'kind': gaussianSplatKind,
    'version': gaussianSplatVersion,
    'format': format,
    'formatVersion': formatVersion,
    'gaussians': gaussians,
    'shDegree': shDegree,
    'fileBytes': fileBytes,
    'maxGaussians': maxGaussians,
    'tool': tool,
    'name': name,
  };

  /// The stereoPair JSON of ImmersiveApi.open
  String toJsonString() => jsonEncode(toJson());

  /// The request [json] holds, null for another kind, version or format, a missing field or a value that cannot be
  /// right, as the Kotlin side reads it
  static GaussianSplatRequest? fromJson(Object? json) {
    if (json is! Map || json['kind'] != gaussianSplatKind || json['version'] != gaussianSplatVersion) {
      return null;
    }
    final format = json['format'];
    final formatVersion = json['formatVersion'];
    final gaussians = json['gaussians'];
    final shDegree = json['shDegree'];
    final fileBytes = json['fileBytes'];
    final maxGaussians = json['maxGaussians'];
    final tool = json['tool'];
    final name = json['name'];
    if ((format != 'spz' && format != 'ply') ||
        formatVersion is! int ||
        formatVersion < 1 ||
        gaussians is! int ||
        gaussians <= 0 ||
        shDegree is! int ||
        shDegree < 0 ||
        shDegree > 4 ||
        fileBytes is! int ||
        fileBytes <= 0 ||
        maxGaussians is! int ||
        maxGaussians <= 0 ||
        (tool != null && tool is! String) ||
        name is! String ||
        name.trim().isEmpty) {
      return null;
    }
    return GaussianSplatRequest(
      format: format as String,
      formatVersion: formatVersion,
      gaussians: gaussians,
      shDegree: shDegree,
      fileBytes: fileBytes,
      maxGaussians: maxGaussians,
      tool: tool as String?,
      name: name,
    );
  }

  @override
  bool operator ==(Object other) =>
      other is GaussianSplatRequest &&
      other.format == format &&
      other.formatVersion == formatVersion &&
      other.gaussians == gaussians &&
      other.shDegree == shDegree &&
      other.fileBytes == fileBytes &&
      other.maxGaussians == maxGaussians &&
      other.tool == tool &&
      other.name == name;

  @override
  int get hashCode => Object.hash(format, formatVersion, gaussians, shDegree, fileBytes, maxGaussians, tool, name);
}
