/// When the rows read the time: the clock of the system; replaced in tests
final conversionClockProvider = Provider<DateTime Function()>((ref) => DateTime.now);

class _JobRow extends ConsumerStatefulWidget {
  const _JobRow({super.key, required this.job});

  final ConversionJob job;

  @override
  ConsumerState<_JobRow> createState() => _JobRowState();
}

class _JobRowState extends ConsumerState<_JobRow> {
  /// The time left the queue told last, and when the row saw it: the row counts it down between two progresses (a
  /// long step tells nothing until it ends)
  Duration? _told;
  DateTime? _toldAt;
  Timer? _tick;

  @override
  void initState() {
    super.initState();
    _follow();
  }

  @override
  void didUpdateWidget(_JobRow oldWidget) {
    super.didUpdateWidget(oldWidget);
    _follow();
  }

  @override
  void dispose() {
    _tick?.cancel();
    super.dispose();
  }

  void _follow() {
    final job = widget.job;
    if (job.remaining != _told || _toldAt == null) {
      _told = job.remaining;
      _toldAt = ref.read(conversionClockProvider)();
    }
    final counting = job.state.isActive && job.remaining != null;
    if (counting) {
      _tick ??= Timer.periodic(const Duration(seconds: 1), (_) {
        if (mounted) {
          setState(() {});
        }
      });
    } else {
      _tick?.cancel();
      _tick = null;
    }
  }

  /// What is left of the job now
  Duration? get _left {
    final told = _told;
    final at = _toldAt;
    if (told == null || at == null) {
      return null;
    }
    final left = told - ref.read(conversionClockProvider)().difference(at);
    return left.isNegative ? Duration.zero : left;
  }

  @override
  Widget build(BuildContext context) {
    final job = widget.job;
    final t = context.t;
    final colors = Theme.of(context).colorScheme;
    final info = ref.watch(conversionJobInfoProvider.select((infos) => infos[job.id]));
    final glb = ref.watch(sceneGlbCopiesProvider.select((copies) => copies[job.id]));
    final notifier = ref.read(conversionQueueProvider.notifier);
    final asset = info?.asset;
    // A version next to its original on a share is made here, then written there (share_publisher.dart): its folder
    // is that of the share, and nothing of it stays here unless the share refused it
    final publish = ref.watch(sharePublisherProvider.select((publishes) => publishes[job.id]));
    final written = publish == null ? job.writtenPath : publish.keptPath;
    final onShare = publish != null && publish.keptPath == null;
    final folder = onShare ? publish.target.folder.label : (written != null ? p.dirname(written) : job.target?.folder);
    final secondary = TextStyle(color: colors.onSurfaceVariant);
    final stage = job.state.isActive ? conversionStageText(t, job) : null;
    final progress = job.state.isActive ? conversionProgressText(t, job, _left) : null;
    final hidden = switch (job.details) {
      SceneResultDetails(:final hiddenFraction) when hiddenFraction > 0 => hiddenFraction,
      _ => null,
    };
    final photo = job.kind.output == ImmersiveKind.stereoPhoto;
    final lines = <Widget>[
      Text(
        [
          conversionKindText(t, job.kind),
          if (job.batchSize > 1) t.ai_immersive_progress_count(index: job.batchIndex, total: job.batchSize),
        ].join('  •  '),
        style: secondary,
      ),
      Text([conversionStateText(t, job), ?stage].join('  •  '), key: const Key('ai_job_state')),
      if (job.state == ConversionState.waiting && job.waitingFor != null)
        Text(
          conversionWaitText(t, job.waitingFor!, free: job.waitingFree),
          key: const Key('ai_job_waiting'),
          style: secondary,
        ),
      if (job.state.isActive) ...[
        const SizedBox(height: 4),
        LinearProgressIndicator(value: job.phase == ConversionPhase.preparing ? null : job.progress),
        if (progress != null) Text(progress, key: const Key('ai_job_time_left'), style: secondary),
      ],
      if (job.skipReason case final reason?)
        Text(conversionSkipText(t, reason, name: job.target?.fileName), style: secondary),
      if (job.state == ConversionState.failed && job.error != null)
        Text(conversionFailureText(t, job.error!, job.message), style: TextStyle(color: colors.error)),
      if (folder != null && !job.state.isEnded || job.state == ConversionState.done) ...[
        if (publish != null && job.state == ConversionState.done && !publish.state.isEnded)
          Text(t.ai_immersive_share_saving, key: const Key('ai_job_share_saving'), style: secondary),
        if (publish?.shown case final shown?)
          SelectableText(shown, key: const Key('ai_job_share_path'), style: secondary)
        else if (written != null)
          SelectableText(written, style: secondary)
        else if (folder != null)
          SelectableText(folder, style: secondary),
      ],
      if (publish?.state == SharePublishState.skipped)
        Text(
          conversionSkipText(t, ConversionSkipReason.nameTaken, name: job.target?.fileName),
          key: const Key('ai_job_share_skipped'),
          style: secondary,
        ),
      if (publish != null && publish.state == SharePublishState.keptHere)
        Text(
          t.ai_immersive_share_kept_here(reason: shareFailureText(t, publish.failure, publish.message)),
          key: const Key('ai_job_share_kept'),
          style: TextStyle(color: colors.error),
        ),
      if (job.state == ConversionState.done) ...[
        if (job.reduced && job.eyeWidth != null) Text(t.ai_immersive_reduced(width: job.eyeWidth!), style: secondary),
        if (hidden != null) Text(t.ai_immersive_hidden_filled(percent: (hidden * 100).round()), style: secondary),
        for (final flag in job.qualityFlags)
          // The share filled in says it better than the flag
          if (flag != ReliefQualityFlag.hiddenAreas || hidden == null) Text(qualityFlagText(t, flag), style: secondary),
        if (info?.serverEdits ?? false) Text(t.ai_immersive_server_edits_ignored, style: secondary),
        if (publish != null ? publish.glbShown : glb?.path case final copy?)
          SelectableText(copy, key: const Key('ai_job_glb'), style: secondary),
        if (glb?.error case final error?)
          Text(
            sceneGlbProblemText(t, error),
            key: const Key('ai_job_glb'),
            style: TextStyle(color: colors.error),
          ),
        if (localOnlyMessage(t, isNetwork: info?.isNetwork ?? false) case final message?)
          Text(message, key: const Key('ai_job_local_only'), style: secondary),
      ],
    ];
    final actions = <Widget>[
      // The card is asked again a little later anyway; Resume asks it now, once the game is closed
      if (job.state == ConversionState.waiting && job.waitingFor == ConversionWait.graphicsMemory)
        TextButton(
          key: const Key('ai_job_check_gpu'),
          onPressed: notifier.checkGraphicsCardAgain,
          child: Text(t.ai_immersive_resume),
        ),
      if (!job.state.isEnded)
        TextButton(key: const Key('ai_job_cancel'), onPressed: () => notifier.cancel(job.id), child: Text(t.cancel)),
      if (job.target != null && (job.state == ConversionState.failed || job.state == ConversionState.cancelled))
        TextButton(
          key: const Key('ai_job_retry'),
          onPressed: () => notifier.retry(job.id),
          child: Text(t.ai_immersive_retry),
        ),
      // On the share: opened there, in the page of the photo of the share
      if (job.state == ConversionState.done && onShare && publish.state == SharePublishState.saved)
        TextButton(
          key: const Key('ai_job_view_share'),
          onPressed: () {
            final open = ref.read(shareVersionViewerProvider);
            unawaited(Navigator.of(context).maybePop());
            open(context, publish.target.folder.sourceId, publish.path!);
          },
          child: Text(t.view),
        ),
      if (job.state == ConversionState.done && written != null) ...[
        // A scene is judged here before it goes to the NAS; the panel stays under the preview for the next one
        if (job.kind == ConversionKind.sceneFromPhoto)
          TextButton(
            key: const Key('ai_job_preview_3d'),
            onPressed: () => ref.read(scenePreviewOpenerProvider)(context, written),
            child: Text(t.ai_immersive_preview_3d),
          ),
        TextButton(
          key: const Key('ai_job_open_folder'),
          onPressed: () => unawaited(ref.read(conversionFolderOpenerProvider)(p.dirname(written))),
          child: Text(t.ai_immersive_open_folder),
        ),
        TextButton(
          key: const Key('ai_job_view'),
          onPressed: () {
            final open = ref.read(versionOpenerProvider);
            unawaited(Navigator.of(context).maybePop());
            open(written);
          },
          child: Text(t.view),
        ),
        TextButton(
          key: const Key('ai_job_delete'),
          onPressed: () async {
            if (await confirmDeleteVersion(context, ref, written, kind: job.kind.output)) {
              notifier.remove(job.id);
            }
          },
          child: Text(photo ? t.ai_immersive_delete_result : t.ai_immersive_delete_version),
        ),
      ],
    ];
    return Padding(
      padding: const EdgeInsets.fromLTRB(12, 6, 12, 6),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          ClipRRect(
            borderRadius: const BorderRadius.all(Radius.circular(4)),
            child: SizedBox.square(
              dimension: 56,
              child: asset == null
                  ? ColoredBox(
                      color: colors.surfaceContainerHighest,
                      child: Icon(Icons.photo_outlined, color: colors.onSurfaceVariant),
                    )
                  : ref.watch(conversionThumbnailProvider)(asset),
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(job.source.name, style: Theme.of(context).textTheme.titleSmall, overflow: TextOverflow.ellipsis),
                ...lines,
                if (actions.isNotEmpty) Wrap(spacing: 4, children: actions),
              ],
            ),
          ),
        ],
      ),
    );
  }
}

/// Why the share refused a version, in the words of the dialog: read only, full, else the words of the share
String shareFailureText(Translations t, ShareWriteFailure? failure, String? message) => switch (failure) {
  ShareWriteFailure.readOnly => t.ai_immersive_failed_read_only,
  ShareWriteFailure.diskFull => t.ai_immersive_failed_disk_full,
  _ => message ?? '',
};

/// Opens a version written on a share in the page of the photos of the share; replaced in tests
final shareVersionViewerProvider = Provider<void Function(BuildContext context, String sourceId, String path)>(
  (ref) => (context, sourceId, path) {
    try {
      unawaited(context.router.push(NetworkPhotoRoute(sourceId: sourceId, path: path)));
    } catch (error) {
      _log.warning('The page of $path could not be opened: $error');
    }
  },
);

/// The thumbnail of the photo of a job; replaced in tests
final conversionThumbnailProvider = Provider<Widget Function(BaseAsset asset)>(
  (ref) =>
      (asset) => Thumbnail.fromAsset(asset: asset, size: const Size.square(112)),
);
