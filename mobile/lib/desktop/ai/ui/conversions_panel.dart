/// The least share of the card the app is said to hold: below it the share is left out. A 0 may be a share the system
/// does not count rather than nothing (Windows has no counter of the app on the NVIDIA card of an Optimus laptop whose
/// app runs on the integrated chip), and a few megabytes would not explain a shortfall
const appGraphicsShareShownFrom = 64 * 1024 * 1024;

/// "360° panoramas need 6.0 GiB of free graphics memory, 5.4 GiB free (Immuch360 itself holds 1.4 GiB): close games,
/// 3D apps or videos", or "Splat scenes need 2.5 GiB ..." for a splat scene: the sentence of the [kind] of the job, the
/// two kinds of the graphics card's lane having needs of their own (gpuNeedOf); the part of the app when it could be
/// read, from [appGraphicsShareShownFrom]
String gpuShortfallText(
  Translations t,
  GpuShortfall shortfall, {
  ConversionKind kind = ConversionKind.panoramaFromPhoto,
}) {
  final needed = formatBytes(shortfall.need);
  final free = formatBytes(shortfall.free);
  final splat = kind == ConversionKind.splatScene;
  return switch (shortfall.appHolds) {
    final app? when app >= appGraphicsShareShownFrom =>
      splat
          ? t.ai_immersive_splat_gpu_budget_need_app(needed: needed, free: free, app: formatBytes(app))
          : t.ai_immersive_gpu_budget_need_app(needed: needed, free: free, app: formatBytes(app)),
    _ =>
      splat
          ? t.ai_immersive_splat_gpu_budget_need(needed: needed, free: free)
          : t.ai_immersive_gpu_budget_need(needed: needed, free: free),
  };
}

