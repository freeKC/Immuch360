        // opens it, its folder holds it
        if (splat)
          TextButton(
            key: const Key('ai_job_splat_headset'),
            onPressed: () => unawaited(_showHeadsetHelp(context, written, isNetwork: info?.isNetwork ?? false)),
            child: Text(t.ai_immersive_splat_how_headset),
          )
        else ...[
          TextButton(
            key: const Key('ai_job_view'),
            onPressed: () {
              final open = ref.read(versionOpenerProvider);
              unawaited(Navigator.of(context).maybePop());
              open(written);
