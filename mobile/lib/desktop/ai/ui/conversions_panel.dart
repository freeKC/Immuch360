// The panel of the 3D conversions of a computer (design-final 2026-10-26, section 5, point 4; spec 5.3 and 5.4): a side
// panel over the window, opened by the button of the app bar and after a launch. Per photo: its thumbnail, its name,
// "2D to 3D SBS", its state in the words of the spec with a bar while it runs, "3 of 12", where its 3D photo goes then
// went, the quality flags of the result, and its actions: Cancel while it waits or runs, Retry once it failed or was
// cancelled; for a 3D photo made, Open folder, View, and Delete this 3D photo, and Preview in 3D for a 3D scene
// (lib/desktop/ai/scene_preview). At the bottom: Cancel all, Retry failed, Clear finished, and Resume when a disk full
// paused the queue.
//
// View opens the 3D photo the way a file given to the program opens (open_files.dart), at once, before any scan.
// Delete this 3D photo asks first, then deletes only a file that still carries our XMP with its DerivativeId, read
// again just before: a file of the user that took its name meanwhile is never deleted (design 4.2). The original is
// never touched.
//
// Phases 2 and 3 (design-final 2026-10-27, section 9.1, point 3): under the honesty label of each type in the queue,
// two sections once the graphics card has a job, "Processor" and "Graphics card"; per job its type ("2D to 3D scene",
// "2D to 360° panorama", "360° to 3D 360°"), the step of a long job in words ("Estimating the geometry"), "step 12 of
// 28, about 3 min left" (the time left counted down between two progresses), why a job still waits (the memory the
// other lane holds), the part of a scene filled in, its .glb copy when one was asked for ("Also save a .glb copy"),
// and "Delete this version" for a version that is not a 3D photo.
//
// The 360° panoramas (lot U3; design-final 2026-10-27, sections 4.5 and 4.7): a job of the graphics card waiting for
// its memory says how much is free, with Resume, which asks the card again at once (checkGraphicsCardAgain); the named
// failures of a generation in their words ("The graphics card ran out of memory: close games or 3D apps and retry",
// "Other apps use the graphics card memory: close games or 3D apps" for a graph cut into segments, "The graphics card
// did not answer"...); the 3D version of a panorama the app generated, chained after it or chosen by itself, comes
// under the sentence of the panorama, "Generated by AI beyond the photo's edges". The section of the graphics card
// comes first: its jobs take minutes, the 3D versions chained after them wait below.

