// The badges of the thumbnails of a computer for the files Immuch360 makes and the photos of two eyes side by side
// (design-final 2026-10-26, sections 4.2 and 4.5; design-final 2026-10-27, section 8.4): "3D AI" on a relief estimated
// by AI from a single photo (a 3D photo, the 3D version of a 360° photo), "3D scene" on a scene rebuilt from one photo,
// "360° AI" on a panorama generated beyond the edges of a photo and on its 3D version, so that the honesty label goes
// wherever such a file shows; "3D" on any other photo of two eyes side by side.
//
// A thumbnail never reads a file. What our XMP says of each file of the folder library is already in its index, read
// by the scan (library_index.dart, the origin and immersive_kind columns), and is read again here at the end of each
// local sync. A photo of another tool is told by the rule of its name and frame (stereo_photo_probe.dart), the one the
// viewer applies before it reads the head of a candidate: the stereo column of the index stays what our XMP declares.

