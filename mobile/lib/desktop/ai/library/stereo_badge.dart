/// The badge a thumbnail shows
enum StereoBadge {
  /// "3D AI": a relief estimated by AI from a single photo, a 3D photo or the 3D version of a 360° photo
  estimatedRelief,

  /// "3D scene": a scene rebuilt from one photo, its hidden areas filled in by AI
  scene,

  /// "360° AI": a panorama generated by AI beyond the edges of a photo, or its 3D version
  generatedPanorama,

  /// "3D": two eyes side by side, made by another tool, or a 3D photo of ours whose origin this build does not know
  stereo,
}

/// The badge of a photo named [name], of [width] x [height] pixels, whose file the library knows as made by Immuch360
/// as [version] (null for any other file). The kind of a version decides; a version the scan has not read again since
/// the index learnt the kinds is told by its origin, and one of a later format whose origin this build does not know
/// gets no badge, never the "3D" of a pair. Another 360° photo keeps its own badge.
StereoBadge? stereoBadgeOf({
  required IndexedVersion? version,
  required String name,
  int? width,
  int? height,
  bool isPanorama = false,
}) {
  if (version != null) {
    final origin = version.origin;
    return switch (version.kind) {
      ImmersiveKind.stereoPhoto => origin == IndexedOrigin.estimated ? StereoBadge.estimatedRelief : StereoBadge.stereo,
      ImmersiveKind.volumetricScene => StereoBadge.scene,
      ImmersiveKind.panorama360 => StereoBadge.generatedPanorama,
      ImmersiveKind.stereoPanorama360 =>
        origin == IndexedOrigin.generated ? StereoBadge.generatedPanorama : StereoBadge.estimatedRelief,
      null => switch (origin) {
        IndexedOrigin.estimated => StereoBadge.estimatedRelief,
        IndexedOrigin.reconstructed => StereoBadge.scene,
        IndexedOrigin.generated => StereoBadge.generatedPanorama,
        IndexedOrigin.other => null,
      },
    };
  }
  if (isPanorama) {
    return null;
  }
  return decideStereoPhoto(name: name, width: width, height: height) == null ? null : StereoBadge.stereo;
}

/// Where the content of each file Immuch360 made comes from and its kind, by asset id, read from the index of the
/// library again each time a local sync ends
final generatedVersionsProvider = FutureProvider<Map<String, IndexedVersion>>((ref) async {
  ref.watch(syncStatusProvider.select((status) => status.localSyncStatus == SyncStatus.success));
  final library = await ref.watch(folderLibraryProvider.future);
  return library.index.generatedVersions();
});

const _shadows = [Shadow(blurRadius: 5.0, color: Color.fromRGBO(0, 0, 0, 0.6))];

/// The badge of the thumbnail of [asset], beside the 360° one; nothing for a photo that is neither one of our versions
/// nor two eyes side by side
class DesktopStereoBadge extends ConsumerWidget {
  const DesktopStereoBadge({super.key, required this.asset});

  final BaseAsset asset;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    if (!asset.isImage) {
      return const SizedBox.shrink();
    }
    final localId = asset.localId;
    final version = localId == null
        ? null
        : ref.watch(generatedVersionsProvider.select((versions) => versions.valueOrNull?[localId]));
    final ordinary =
        version == null && decideStereoPhoto(name: asset.name, width: asset.width, height: asset.height) == null;
    if (ordinary) {
      // Nothing more is asked of an ordinary photo
      return const SizedBox.shrink();
    }
    final badge = stereoBadgeOf(
      version: version,
      name: asset.name,
      width: asset.width,
      height: asset.height,
      // Our XMP decides for our files; the 360° rules are asked of another tool's file only
      isPanorama: version == null && ref.watch(isPanoramaProvider(asset)),
    );
    if (badge == null) {
      return const SizedBox.shrink();
    }
    final t = context.t;
    // "3D" is the same word in every language, as on the tiles of the shares; the others carry their honesty label
    final (text, key, honesty) = switch (badge) {
      StereoBadge.estimatedRelief => (t.ai_immersive_badge, 'desktop_badge_3d_ai', t.ai_immersive_relief_estimated),
      StereoBadge.scene => (t.ai_immersive_badge_scene, 'desktop_badge_scene', t.ai_immersive_scene_honesty),
      StereoBadge.generatedPanorama => (
        t.ai_immersive_badge_360,
        'desktop_badge_360_ai',
        t.ai_immersive_panorama_honesty,
      ),
      StereoBadge.stereo => ('3D', 'desktop_badge_3d', null),
    };
    final label = Padding(
      padding: const EdgeInsets.only(right: 10.0, top: 6.0),
      child: Text(
        text,
        key: Key(key),
        style: const TextStyle(color: Colors.white, fontSize: 12, fontWeight: FontWeight.w700, shadows: _shadows),
      ),
    );
    return honesty == null ? label : Tooltip(message: honesty, child: label);
  }
}
